-- ============================================================================
-- 비밀번호 해싱(PBKDF2)을 위한 pwd 컬럼 폭 확대
-- ----------------------------------------------------------------------------
-- 배경: PBKDF2 해시는 약 83자 형식 "pbkdf2$120000$<saltBase64>$<hashBase64>" 인데
--       기존 pwd 컬럼은 MEMBER VARCHAR2(30), STUDENT/TEACHER VARCHAR2(40) 로 좁다.
--       → 신규 가입 시 해시 INSERT가 ORA-12899(값이 너무 큼)로 실패하고,
--         DAO가 예외를 삼켜(rollback 후 0 반환) 가입은 "성공"처럼 보이지만
--         실제 행이 안 들어가 로그인이 안 된다.
--       기존 평문 계정은 값이 짧아 들어가고 폴백 비교로 로그인되지만,
--       비밀번호를 변경하면 동일 문제가 발생한다.
--
-- ⚠️ 이 DDL을 실행해야 비밀번호 해싱(신규 가입/변경 → 로그인)이 정상 동작한다.
--    widening(폭 확대)이라 기존 데이터 손실 없음. 스키마 소유 계정으로 실행.
-- ============================================================================
ALTER TABLE MEMBER  MODIFY (pwd VARCHAR2(200));
ALTER TABLE STUDENT MODIFY (pwd VARCHAR2(200));
ALTER TABLE TEACHER MODIFY (pwd VARCHAR2(200));

-- 적용 후: 신규 가입 → 로그인 → 탈퇴까지 해시 기반으로 동작.
-- (기존 평문 계정은 다음 비밀번호 변경 시 자동으로 해시로 전환된다.)
