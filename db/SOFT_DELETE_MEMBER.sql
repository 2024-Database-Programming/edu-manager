-- ============================================================================
-- 회원 "소프트 삭제(soft delete)"를 위한 status 컬럼 추가
-- ----------------------------------------------------------------------------
-- 배경: 기존 탈퇴는 DELETE FROM MEMBER 였고, BEFORE DELETE 트리거(TRG_MEMBER_CLEANUP)가
--       자식 행(수강신청·과제제출·후기·좋아요 등)을 연쇄 삭제했다. 그 결과
--         · 강사를 지우면 그 강의를 듣던 "다른 학생들"의 수강/제출 이력까지 사라지고,
--         · 스터디 리더를 지우면 StudyGroup.leaderId 가 없는 회원을 가리켜 무결성이 깨졌다.
--
--       → 정책을 소프트 삭제 + 익명화로 전환한다. 회원 행은 남기되
--         status='WITHDRAWN' 으로 표시하고 개인정보(name/email/phone/pwd)는 스크럽한다.
--         이력·후기·강의·스터디는 보존되고, 작성자만 "(탈퇴회원)"으로 표기된다.
--
-- ⚠️ 이 DDL을 먼저 실행해야 한다. 신규 코드가 MEMBER.status 를 참조하므로
--    컬럼이 없으면 로그인/회원목록/탈퇴 쿼리가 ORA-00904(invalid identifier)로 실패한다.
--    DEFAULT 'ACTIVE' 라 기존 회원은 모두 자동으로 ACTIVE 가 된다(데이터 손실 없음).
-- ============================================================================
ALTER TABLE MEMBER ADD (status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL);

-- 참고: 이제 탈퇴는 UPDATE(소프트 삭제)로 처리되어 DELETE FROM MEMBER 가 일어나지 않으므로
--       TRG_MEMBER_CLEANUP 트리거는 더 이상 발화하지 않는다(휴면 상태).
--       관리자가 SQL 로 직접 하드 삭제할 때를 대비한 안전망으로 그대로 두어도 무방하다.
--       완전히 제거하려면 아래 주석을 해제해 실행한다.
-- DROP TRIGGER TRG_MEMBER_CLEANUP;
